static void getColorRgb(const std::string& color, uint8_t& r, uint8_t& g, uint8_t& b) {
    if (color == "[97m") { r = 255; g = 255; b = 255; }
    else if (color == "[92m") { r = 85; g = 255; b = 85; }
    else if (color == "[96m") { r = 85; g = 255; b = 255; }
    else if (color == "[91m") { r = 255; g = 85; b = 85; }
    else if (color == "[95m") { r = 255; g = 85; b = 255; }
    else if (color.find("90") != std::string::npos) { r = 85; g = 85; b = 85; }
    else { r = 255; g = 255; b = 85; }
}

bool ImageExporter::exportToFile(const std::vector<std::vector<CanvasCell>>& grid,
                                 const std::string& filename,
                                 const std::string& format) {
    int rows = static_cast<int>(grid.size());
    if (rows == 0) return false;
    int cols = static_cast<int>(grid[0].size());
    if (cols == 0) return false;

    const int CELL_W = 8;
    const int CELL_H = 16;
    const int SCALE = 2;

    int imgW = cols * CELL_W * SCALE;
    int imgH = rows * CELL_H * SCALE;

    std::vector<uint8_t> pixels(imgW * imgH * 3);

    for (int y = 0; y < imgH; ++y) {
        for (int x = 0; x < imgW; ++x) {
            int idx = (y * imgW + x) * 3;
            pixels[idx + 0] = 0;
            pixels[idx + 1] = 0;
            pixels[idx + 2] = 168;
        }
    }

    auto putDot = [&](int px, int py, uint8_t r, uint8_t g, uint8_t b) {
        if (px < 0 || px >= cols * CELL_W || py < 0 || py >= rows * CELL_H) return;
        for (int sy = 0; sy < SCALE; ++sy) {
            for (int sx = 0; sx < SCALE; ++sx) {
                int outX = px * SCALE + sx;
                int outY = py * SCALE + sy;
                int idx = (outY * imgW + outX) * 3;
                pixels[idx + 0] = r;
                pixels[idx + 1] = g;
                pixels[idx + 2] = b;
            }
        }
    };

    for (int r = 0; r < rows; ++r) {
        for (int c = 0; c < cols; ++c) {
            const auto& cell = grid[r][c];
            if (cell.ch == " " || cell.ch.empty()) continue;

            uint8_t fr, fg, fb;
            getColorRgb(cell.color, fr, fg, fb);

            int startX = c * CELL_W;
            int startY = r * CELL_H;

            if (cell.ch == "─") {
                for (int x = 0; x < CELL_W; ++x) {
                    putDot(startX + x, startY + 7, fr, fg, fb);
                    putDot(startX + x, startY + 8, fr, fg, fb);
                }
            } else if (cell.ch == "│") {
                for (int y = 0; y < CELL_H; ++y) {
                    putDot(startX + 3, startY + y, fr, fg, fb);
                    putDot(startX + 4, startY + y, fr, fg, fb);
                }
            } else if (cell.ch == "┌") {
                for (int x = 3; x < CELL_W; ++x) {
                    putDot(startX + x, startY + 7, fr, fg, fb);
                    putDot(startX + x, startY + 8, fr, fg, fb);
                }
                for (int y = 7; y < CELL_H; ++y) {
                    putDot(startX + 3, startY + y, fr, fg, fb);
                    putDot(startX + 4, startY + y, fr, fg, fb);
                }
            } else if (cell.ch == "┐") {
                for (int x = 0; x <= 4; ++x) {
                    putDot(startX + x, startY + 7, fr, fg, fb);
                    putDot(startX + x, startY + 8, fr, fg, fb);
                }
                for (int y = 7; y < CELL_H; ++y) {
                    putDot(startX + 3, startY + y, fr, fg, fb);
                    putDot(startX + 4, startY + y, fr, fg, fb);
                }
            } else if (cell.ch == "└") {
                for (int x = 3; x < CELL_W; ++x) {
                    putDot(startX + x, startY + 7, fr, fg, fb);
                    putDot(startX + x, startY + 8, fr, fg, fb);
                }
                for (int y = 0; y <= 8; ++y) {
                    putDot(startX + 3, startY + y, fr, fg, fb);
                    putDot(startX + 4, startY + y, fr, fg, fb);
                }
            } else if (cell.ch == "┘") {
                for (int x = 0; x <= 4; ++x) {
                    putDot(startX + x, startY + 7, fr, fg, fb);
                    putDot(startX + x, startY + 8, fr, fg, fb);
                }
                for (int y = 0; y <= 8; ++y) {
                    putDot(startX + 3, startY + y, fr, fg, fb);
                    putDot(startX + 4, startY + y, fr, fg, fb);
                }
            } else if (cell.ch == "·" || cell.ch == ".") {
                putDot(startX + 3, startY + 7, fr, fg, fb);
                putDot(startX + 4, startY + 7, fr, fg, fb);
                putDot(startX + 3, startY + 8, fr, fg, fb);
                putDot(startX + 4, startY + 8, fr, fg, fb);
            } else if (cell.ch == "╲") {
                for (int y = 0; y < CELL_H; ++y) {
                    int x = (y * CELL_W) / CELL_H;
                    putDot(startX + x, startY + y, fr, fg, fb);
                }
            } else if (cell.ch == "╱") {
                for (int y = 0; y < CELL_H; ++y) {
                    int x = CELL_W - 1 - (y * CELL_W) / CELL_H;
                    putDot(startX + x, startY + y, fr, fg, fb);
                }
            } else if (cell.ch.size() == 1) {
                unsigned char ch = static_cast<unsigned char>(cell.ch[0]);
                if (ch >= 32 && ch <= 126) {
                    const uint8_t* glyph = FONT_DATA[ch - 32];
                    for (int gy = 0; gy < 16; ++gy) {
                        for (int gx = 0; gx < 8; ++gx) {
                            if (glyph[gy] & (1 << (7 - gx))) {
                                putDot(startX + gx, startY + gy, fr, fg, fb);
                            }
                        }
                    }
                }
            }
        }
    }

    if (format == "bmp") {
        return stbi_write_bmp(filename.c_str(), imgW, imgH, 3, pixels.data()) != 0;
    } else if (format == "jpg" || format == "jpeg") {
        return stbi_write_jpg(filename.c_str(), imgW, imgH, 3, pixels.data(), 90) != 0;
    } else {
        return stbi_write_png(filename.c_str(), imgW, imgH, 3, pixels.data(), imgW * 3) != 0;
    }
}
